def generate_questions(region=None):
    data = COUNTRIES

    if region:
        data = [c for c in COUNTRIES if c[2] == region]

    questions = []
    capitals = [c[1] for c in data]

    for country, capital, _ in data:
        wrong = random.sample([x for x in capitals if x != capital], 3)
        options = wrong + [capital]
        random.shuffle(options)

        questions.append({
            "country": country,
            "capital": capital,
            "options": options
        })

    return questions